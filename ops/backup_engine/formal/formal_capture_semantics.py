        require(manifest['schemaVersion'] == 'RepositoryManifest/v1' and
            manifest['backupId'] == index['backupId'] and manifest['generationId'] == index['generationId'] and
            manifest['commonRecoveryPoint'] == index['recoveryPoint'] and
            index['inventoryPin'] in manifest['payloadRefs'] and index['exportReceiptPin'] in manifest['payloadRefs'],
            'FORMAL_CAPTURE_SEMANTIC_PARENT_CHANGED')
        inventory = read(pin(index['inventoryPin']), allow_empty=True)
        receipt = strict_document(read(pin(index['exportReceiptPin'])), 64*1024*1024)
        require(receipt['inventorySha256'] == digest(inventory) and receipt['inventoryBytes'] == len(inventory),
            'FORMAL_CAPTURE_SEMANTIC_PARENT_CHANGED')
        rows = [strict_document(line, 1048576) for line in inventory.splitlines()]
