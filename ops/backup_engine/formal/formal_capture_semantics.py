    def queries(self, mysql, database, guard):
        require(type(database) is str and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_-]{0,63}', database), 'FORMAL_CAPTURE_REFERENCE_DATABASE_INVALID')
        guard(); mysql.query('SHOW TABLES FROM `'+database+'`;'); observations = []
        for query in self.reference_recipe['referenceQueries']:
            guard(); described = mysql.query('DESCRIBE `'+database+'`.`'+query['table']+'`;')
            columns = {row.split('\t')[0] for row in described.splitlines()}
            require(set(query['columns']) <= columns, 'FORMAL_CAPTURE_REFERENCE_COLUMN_MISSING')
            sql = 'SELECT '+','.join('HEX(CAST(`'+c+'` AS BINARY))' for c in query['columns'])+ \
                ' FROM `'+database+'`.`'+query['table']+'`;'
            rows = decode_rows(bounded_reference_query(mysql, sql, guard), query, self.reference_recipe['maxRows'])
            observations.extend(rows); guard()
