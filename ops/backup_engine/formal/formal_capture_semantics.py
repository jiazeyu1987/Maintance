    @staticmethod
    def verify_content(reference, guard):
        pin(reference); path = Path(reference['path']); guard()
        require(path.is_absolute() and all(not p.is_symlink() and p.resolve() == p for p in (path, *path.parents)),
            'FORMAL_CAPTURE_OBJECT_PARENT_CHANGED')
        before = path.lstat()
        def identity(i): return (i.st_dev, i.st_ino, i.st_mode, i.st_nlink, i.st_size, i.st_mtime_ns, i.st_ctime_ns)
        require(stat.S_ISREG(before.st_mode) and before.st_nlink == 1, 'FORMAL_CAPTURE_OBJECT_PARENT_CHANGED')
        sha = hashlib.sha256(); size = 0
        with path.open('rb') as stream:
            require(identity(os.fstat(stream.fileno())) == identity(before), 'FORMAL_CAPTURE_OBJECT_PARENT_CHANGED')
            while True:
                guard(); chunk = stream.read(1024*1024)
                if not chunk: break
                size += len(chunk); require(size <= reference['bytes'], 'FORMAL_CAPTURE_OBJECT_PARENT_CHANGED')
                sha.update(chunk)
            require(identity(os.fstat(stream.fileno())) == identity(before), 'FORMAL_CAPTURE_OBJECT_PARENT_CHANGED')
        require(identity(path.lstat()) == identity(before) and size == reference['bytes'] and
            sha.hexdigest() == reference['sha256'], 'FORMAL_CAPTURE_OBJECT_PARENT_CHANGED')
        guard()

